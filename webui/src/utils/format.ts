export function fmtNum(n: number | null | undefined): string {
  if (n == null || Number.isNaN(Number(n))) return '-';
  return Number(n).toLocaleString('en-US');
}

export function fmtCompact(n: number | null | undefined): string {
  if (n == null || Number.isNaN(Number(n))) return '-';
  const v = Number(n);
  const abs = Math.abs(v);
  if (abs >= 1e9) return `${(v / 1e9).toFixed(2)}B`;
  if (abs >= 1e6) return `${(v / 1e6).toFixed(2)}M`;
  if (abs >= 1e3) return `${(v / 1e3).toFixed(1)}K`;
  return String(v);
}

export function fmtSec(v: number | null | undefined): string {
  if (v == null || Number.isNaN(Number(v))) return '-';
  return `${Number(v).toFixed(2)}s`;
}

export function fmtTps(v: number | null | undefined): string {
  if (v == null || Number.isNaN(Number(v))) return '-';
  return `${Number(v).toFixed(1)}/s`;
}

export function fmtPct(v: number | null | undefined): string {
  if (v == null || Number.isNaN(Number(v))) return '-';
  return `${Number(v).toFixed(1)}%`;
}

export function shortModel(m: string | null | undefined): string {
  if (!m) return '-';
  return m
    .replace('Gemini ', 'G')
    .replace('Claude ', 'C ')
    .replace(' (XHigh)', ' XH')
    .replace(' (High)', ' H')
    .replace(' (Medium)', ' M')
    .replace(' (Low)', ' L');
}

export function localDateKey(dt: Date = new Date()): string {
  const y = dt.getFullYear();
  const m = String(dt.getMonth() + 1).padStart(2, '0');
  const d = String(dt.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

export function ctxToneVar(pct: number | null | undefined): string {
  if (pct == null || Number.isNaN(Number(pct))) {
    return 'var(--md-sys-color-on-surface-variant)';
  }
  const v = Number(pct);
  if (v >= 80) return 'var(--tm-status-danger)';
  if (v >= 60) return 'var(--tm-status-warn)';
  return 'var(--tm-status-ok)';
}

